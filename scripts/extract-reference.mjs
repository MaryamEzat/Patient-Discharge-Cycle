// One-time migration extraction of constants and pure presentation mapping, not HTML rendering.
import fs from "node:fs";
const source = fs.readFileSync("Patient Discharge.html", "utf8");
const section = (a, b) => source.slice(source.indexOf(a), source.indexOf(b));
let config = section("        const CONFIG =", "        const CHOICE_MAPS =")
  .trim()
  .replace("const CONFIG", "export const CONFIG");
config = config.replace(
  /\s*dischargeAlertCandidates:.*\n/,
  "\n                alert: 'and_whatsappnotification',\n",
);
config = config.replace("gender: 'crad2_gender'", "gender: 'new_gender'");
config = config.replace(
  "fileScanStatus: ['new_filescanstatus'",
  "fileScanStatus: ['cr301_filescanstatus', 'new_filescanstatus'",
);
config = config.replace(
  "countOfPatients: 'and_countofpatients'",
  "countOfPatients: 'crda1_countofpatients'",
);
config = config.replace(
  "patientCode: ['crad2_patientcode'",
  "patientCode: ['_and_patientcode_value', 'crad2_patientcode'",
);
const start = config.indexOf("inpatientFields:"),
  end = config.indexOf("inpatientAliases:");
config =
  config.slice(0, start) +
  config
    .slice(start, end)
    .replace("patientId: 'new_patientid'", "patientId: 'and_name'")
    .replace("visitId: 'crda1_visitid'", "visitId: 'and_visitid'") +
  config.slice(end);
fs.writeFileSync(
  "src/config/reference.ts",
  "// Field references from original HTML; runtime schema is generated by Power Apps.\n" +
    config +
    "\n",
);
let choices = section(
  "        const CHOICE_MAPS =",
  "        function normalizeGuid",
)
  .trim()
  .replace("const CHOICE_MAPS", "export const CHOICE_MAPS")
  .replace("const FIELD_CHOICE_MAPS", "export const FIELD_CHOICE_MAPS");
fs.writeFileSync("src/config/choices.ts", choices + "\n");
fs.mkdirSync("src/presentation", { recursive: true });
const mapping = section(
  "        function getPatientDisplayData(r)",
  "        function renderTodayKpis",
);
const inpatient = section(
  "        function getInpatientDisplayData(row)",
  "        function buildEarlyPatientPayload",
);
fs.writeFileSync(
  "src/presentation/reference.js",
  "import { CONFIG } from '../config/reference';\nimport { displayValue, displayChoice, displayDateTime, firstDisplayValue, firstDisplayDateTime } from './format';\n" +
    (mapping + inpatient).replaceAll("        function ", "export function "),
);
